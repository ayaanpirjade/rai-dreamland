/**
 * One-off helper: downloads the woff2 files for the three typefaces we use and
 * writes a local @font-face stylesheet into src/styles/fonts.css.
 *
 * Self-hosting keeps the site fully offline-capable and avoids third-party
 * font CDNs going down (or blocking) right before a birthday. Run with:
 *   node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const outDir = resolve(root, 'public/fonts')

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36'

/** @type {{family:string, query:string, slug:string, weights:number[]}[]} */
const families = [
  { family: 'Fredoka', query: 'Fredoka:wght@400;500;600;700', slug: 'fredoka', weights: [400, 500, 600, 700] },
  { family: 'Nunito', query: 'Nunito:wght@400;600;700;800', slug: 'nunito', weights: [400, 600, 700, 800] },
  { family: 'Pacifico', query: 'Pacifico', slug: 'pacifico', weights: [400] },
]

const KEEP_SUBSETS = new Set(['latin', 'latin-ext'])

async function main() {
  await mkdir(outDir, { recursive: true })
  const cssParts = []

  for (const fam of families) {
    const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(
      fam.query,
    ).replace(/%3A/g, ':').replace(/%3B/g, ';').replace(/%40/g, '@')}&display=swap`
    const res = await fetch(url, { headers: { 'User-Agent': UA } })
    if (!res.ok) throw new Error(`Font CSS failed for ${fam.family}: ${res.status}`)
    const css = await res.text()

    // Google's CSS emits one @font-face block per unicode-range subset.
    const blocks = css.split('@font-face').slice(1)
    let index = 0
    for (const block of blocks) {
      const subset = (block.match(/\/\*\s*([a-z-]+)\s*\*\//) || [])[1] || `subset${index}`
      if (!KEEP_SUBSETS.has(subset)) continue
      const src = (block.match(/url\((https:[^)]+\.woff2)\)/) || [])[1]
      const weight = (block.match(/font-weight:\s*([0-9]+)/) || [])[1] || '400'
      const style = (block.match(/font-style:\s*([a-z]+)/) || [])[1] || 'normal'
      const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1]
      if (!src) continue

      const fileName = `${fam.slug}-${weight}-${subset}.woff2`
      const bin = await fetch(src, { headers: { 'User-Agent': UA } })
      if (!bin.ok) throw new Error(`Font file failed: ${src} (${bin.status})`)
      await writeFile(resolve(outDir, fileName), Buffer.from(await bin.arrayBuffer()))

      cssParts.push(
        `@font-face {\n  font-family: '${fam.family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('/fonts/${fileName}') format('woff2');${
          range ? `\n  unicode-range: ${range};` : ''
        }\n}`,
      )
      index += 1
      console.log(`saved ${fileName}`)
    }
  }

  const header = `/* Auto-generated by scripts/fetch-fonts.mjs - do not edit by hand. */\n\n`
  await writeFile(resolve(root, 'src/styles/fonts.css'), header + cssParts.join('\n\n') + '\n')
  console.log('wrote src/styles/fonts.css')
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
